#!/usr/bin/env python3
"""Single source → app, backend and live preview.

Inputs : countries.tsv (ISO, dial code, nationality), occupations.tsv
Names  : country names in Arabic/English from CLDR (Babel), so they stay
         correct and consistent across platforms.
Outputs: mobile/lib/shared/reference/reference_data.dart
         backend/src/reference/reference.json
         preview/index.html (block between REFERENCE-DATA markers)
Run    : python3 shared/reference/generate.py   (requires `pip install babel`)
"""
import json, os, re
from babel import Locale

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
here = lambda *p: os.path.join(ROOT, *p)
EN, AR = Locale('en').territories, Locale('ar').territories

def rows(name):
    for line in open(here('shared/reference', name), encoding='utf-8'):
        line = line.rstrip('\n')
        if line and not line.startswith('#'):
            yield line.split('\t')

countries, nationalities = [], {}
for iso, dial, nat in rows('countries.tsv'):
    if nat.startswith('='):
        nat_iso = nat[1:]
    else:
        en, ar = nat.split('|')
        nationalities[iso] = {'iso': iso, 'en': en, 'ar': ar}
        nat_iso = iso
    countries.append({'iso': iso, 'dial': dial, 'en': EN[iso], 'ar': AR[iso], 'nationality': nat_iso})
for c in countries:
    assert c['nationality'] in nationalities, c
countries.sort(key=lambda c: c['en'])
nats = sorted(nationalities.values(), key=lambda n: n['en'])
occupations = [{'key': k, 'category': cat, 'en': en, 'ar': ar} for k, cat, en, ar in rows('occupations.tsv')]
assert len({o['key'] for o in occupations}) == len(occupations), 'duplicate occupation key'
religions, sects = [], []
for kind, key, en, ar in rows('religions.tsv'):
    if kind == 'R':
        religions.append({'key': key, 'en': en, 'ar': ar})
    else:
        rel, sk = key.split('.', 1)
        assert any(r['key'] == rel for r in religions), key
        sects.append({'key': sk, 'religion': rel, 'en': en, 'ar': ar})
assert len({r['key'] for r in religions}) == len(religions)
assert len({(x['religion'], x['key']) for x in sects}) == len(sects)

flag = lambda iso: ''.join(chr(0x1F1E6 + ord(ch) - 65) for ch in iso)
q = lambda s: "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

# ── Dart ──
dart = ['// GENERATED by shared/reference/generate.py — do not edit by hand.', '// ignore_for_file: lines_longer_than_80_chars', '',
'class Country {',
'  const Country(this.iso, this.dial, this.flag, this.ar, this.en, this.nationality);',
'  final String iso;', '  final String dial;', '  final String flag;', '  final String ar;', '  final String en;',
'  /// Default nationality for residents (territories map to their sovereign state).',
'  final String nationality;',
"  String label(String lang) => lang == 'ar' ? ar : en;", '}', '',
'class Nationality {',
'  const Nationality(this.iso, this.en, this.ar);', '  final String iso;', '  final String en;', '  final String ar;',
'  /// Arabic demonyms are stored masculine; the feminine adds ة (مصري → مصرية).',
"  String label(String lang, {bool female = false}) => lang == 'ar' ? (female && ar.endsWith('ي') && !ar.contains(' ') ? '${ar}ة' : ar) : en;",
'}', '',
'class Occupation {',
'  const Occupation(this.key, this.category, this.en, this.ar);', '  final String key;', '  final String category;', '  final String en;', '  final String ar;',
"  String label(String lang) => lang == 'ar' ? ar : en;", '}', '',
'const kCountries = <Country>[']
dart += [f"  Country({q(c['iso'])}, {q(c['dial'])}, {q(flag(c['iso']))}, {q(c['ar'])}, {q(c['en'])}, {q(c['nationality'])})," for c in countries]
dart += ['];', '', 'const kNationalities = <Nationality>[']
dart += [f"  Nationality({q(n['iso'])}, {q(n['en'])}, {q(n['ar'])})," for n in nats]
dart += ['];', '', 'const kOccupations = <Occupation>[']
dart += [f"  Occupation({q(o['key'])}, {q(o['category'])}, {q(o['en'])}, {q(o['ar'])})," for o in occupations]
dart += ['];', '',
'class Religion {',
'  const Religion(this.key, this.en, this.ar);', '  final String key;', '  final String en;', '  final String ar;',
"  String label(String lang) => lang == 'ar' ? ar : en;",
'  List<Sect> get sects => [for (final s in kSects) if (s.religion == key) s];', '}', '',
'class Sect {',
'  const Sect(this.religion, this.key, this.en, this.ar);', '  final String religion;', '  final String key;', '  final String en;', '  final String ar;',
"  String label(String lang) => lang == 'ar' ? ar : en;", '}', '',
'const kReligions = <Religion>[']
dart += [f"  Religion({q(r['key'])}, {q(r['en'])}, {q(r['ar'])})," for r in religions]
dart += ['];', '', 'const kSects = <Sect>[']
dart += [f"  Sect({q(x['religion'])}, {q(x['key'])}, {q(x['en'])}, {q(x['ar'])})," for x in sects]
dart += ['];', '',
'Religion? religionByKey(String? key) => key == null ? null : _religionIndex[key];',
'Sect? sectOf(String? religion, String? key) => religion == null || key == null ? null : _sectIndex[\'$religion.$key\'];',
'final _religionIndex = {for (final r in kReligions) r.key: r};',
"final _sectIndex = {for (final s in kSects) '${s.religion}.${s.key}': s};", '',
'final _countryIndex = {for (final c in kCountries) c.iso: c};',
'final _nationalityIndex = {for (final n in kNationalities) n.iso: n};',
'final _occupationIndex = {for (final o in kOccupations) o.key: o};', '',
"Country countryByIso(String iso) => _countryIndex[iso.toUpperCase()] ?? _countryIndex['AE']!;",
'Country? countryOrNull(String? iso) => iso == null ? null : _countryIndex[iso.toUpperCase()];',
'Nationality? nationalityByIso(String? iso) => iso == null ? null : _nationalityIndex[iso.toUpperCase()];',
'Occupation? occupationByKey(String? key) => key == null ? null : _occupationIndex[key];',
'', '/// Longest-prefix match of a dial code, e.g. +9715… → AE.',
'Country? countryForDial(String e164) {',
'  Country? best;',
'  for (final c in kCountries) {',
'    if (e164.startsWith(c.dial) && (best == null || c.dial.length > best.dial.length)) best = c;',
'  }',
'  return best;', '}', '']
os.makedirs(here('mobile/lib/shared/reference'), exist_ok=True)
open(here('mobile/lib/shared/reference/reference_data.dart'), 'w', encoding='utf-8').write('\n'.join(dart))

# ── Backend ──
os.makedirs(here('backend/src/reference'), exist_ok=True)
json.dump({'countries': [c['iso'] for c in countries],
           'countryNationality': {c['iso']: c['nationality'] for c in countries},
           'nationalities': [n['iso'] for n in nats],
           'occupations': [o['key'] for o in occupations],
           'religions': [r['key'] for r in religions],
           'sects': {r['key']: [x['key'] for x in sects if x['religion'] == r['key']] for r in religions}},
          open(here('backend/src/reference/reference.json'), 'w'), indent=0)

# ── Preview ──
p = here('preview/index.html'); s = open(p, encoding='utf-8').read()
block = ('/*REFERENCE-DATA:BEGIN*/const REF=' + json.dumps({'countries': [[c['iso'], c['dial'], flag(c['iso']), c['ar'], c['en'], c['nationality']] for c in countries],
         'nationalities': [[n['iso'], n['en'], n['ar']] for n in nats], 'occupations': [[o['key'], o['category'], o['en'], o['ar']] for o in occupations],
         'religions': [[r['key'], r['en'], r['ar'], [[x['key'], x['en'], x['ar']] for x in sects if x['religion'] == r['key']]] for r in religions]},
         ensure_ascii=False, separators=(',', ':')) + ';/*REFERENCE-DATA:END*/')
if '/*REFERENCE-DATA:BEGIN*/' in s:
    s = re.sub(r'/\*REFERENCE-DATA:BEGIN\*/.*?/\*REFERENCE-DATA:END\*/', lambda _: block, s, flags=re.S)
    open(p, 'w', encoding='utf-8').write(s)
# ── SQL seed for the migration ──
sq = lambda v: "'" + v.replace("'", "''") + "'"
sql = ['-- GENERATED by shared/reference/generate.py from religions.tsv', 'INSERT INTO religions (key, name_en, name_ar, sort_order) VALUES']
sql += [',\n'.join(f"  ({sq(r['key'])}, {sq(r['en'])}, {sq(r['ar'])}, {i})" for i, r in enumerate(religions)) + '\nON CONFLICT (key) DO UPDATE SET name_en = EXCLUDED.name_en, name_ar = EXCLUDED.name_ar, sort_order = EXCLUDED.sort_order;']
sql += ['INSERT INTO sects (religion_key, key, name_en, name_ar, sort_order) VALUES']
sql += [',\n'.join(f"  ({sq(x['religion'])}, {sq(x['key'])}, {sq(x['en'])}, {sq(x['ar'])}, {i})" for i, x in enumerate(sects)) + '\nON CONFLICT (religion_key, key) DO UPDATE SET name_en = EXCLUDED.name_en, name_ar = EXCLUDED.name_ar, sort_order = EXCLUDED.sort_order;']
open(here('backend/prisma/reference_religions.sql'), 'w', encoding='utf-8').write('\n'.join(sql) + '\n')
print(f'{len(religions)} religions, {len(sects)} sects')
print(f'{len(countries)} countries, {len(nats)} nationalities, {len(occupations)} occupations')
