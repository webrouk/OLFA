import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsIn, IsISO31661Alpha2, IsOptional, IsString, Length, Matches, MaxLength } from 'class-validator';

export class RequestOtpDto {
  @ApiProperty({ example: '+971' })
  @Matches(/^\+\d{1,4}$/)
  dialCode: string;

  @ApiProperty({ example: '50 123 4567' })
  @IsString()
  @Length(4, 20)
  nationalNumber: string;

  @ApiProperty({ example: 'AE' })
  @IsISO31661Alpha2()
  country: string;

  @ApiProperty({ description: 'Stable per-install id generated by the app' })
  @IsString()
  @Length(8, 80)
  deviceId: string;
}

export class VerifyOtpDto {
  @ApiProperty() @IsString() challengeId: string;
  @ApiProperty({ example: '123456' }) @Matches(/^\d{6}$/) code: string;
  @ApiProperty() @IsString() @Length(8, 80) deviceId: string;
  @ApiProperty({ enum: ['ios', 'android', 'web'] }) @IsIn(['ios', 'android', 'web']) platform: 'ios' | 'android' | 'web';
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(20) appVersion?: string;
  @ApiPropertyOptional({ enum: ['ar', 'en', 'fr'] }) @IsOptional() @IsIn(['ar', 'en', 'fr']) locale?: 'ar' | 'en' | 'fr';
  @ApiPropertyOptional({ example: 'Asia/Dubai' }) @IsOptional() @IsString() @MaxLength(64) timezone?: string;
}

export class RefreshDto {
  @ApiProperty() @IsString() @Length(20, 200) refreshToken: string;
}

export class PushTokenDto {
  @ApiProperty() @IsString() @Length(20, 4096) fcmToken: string;
}

export class OtpChallengeResponse {
  @ApiProperty() challengeId: string;
  @ApiProperty() expiresInSeconds: number;
  @ApiProperty() resendAfterSeconds: number;
}

export class TokensResponse {
  @ApiProperty() accessToken: string;
  @ApiProperty() accessTokenExpiresIn: number;
  @ApiProperty() refreshToken: string;
  @ApiProperty() isNewUser: boolean;
  @ApiProperty({ enum: ['PENDING_VERIFICATION', 'ACTIVE', 'REJECTED', 'SUSPENDED', 'RESTRICTED', 'DELETED'] }) accountStatus: string;
  @ApiProperty() profileComplete: boolean;
}
